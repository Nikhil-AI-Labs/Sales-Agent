/**
 * Query fabric specifications
 */
export function queryFabricSpecs(filters: {
  size?: string;
  grammage?: number;
  quality?: string;
}): FabricSpec[] {
  return FABRIC_CATALOG.filter((fabric) => {
    if (filters.size && fabric.size_inches !== filters.size) return false;
    if (filters.grammage && fabric.grammage_gpm !== filters.grammage) return false;
    if (filters.quality && fabric.quality.toLowerCase() !== filters.quality.toLowerCase()) return false;
    return true;
  });
}

/**
 * Find matching fabric for natural language query
 */
export function findMatchingFabric(query: string): FabricSpec[] {
  const lowerQuery = query.toLowerCase();
  
  // Extract size if mentioned
  const sizeMatch = lowerQuery.match(/(\d+)\s*(?:inch|inches|")/);
  const size = sizeMatch ? sizeMatch[1] : undefined;

  // Extract grammage if mentioned
  const grammageMatch = lowerQuery.match(/(\d+\.?\d*)\s*g/);
  const grammage = grammageMatch ? parseFloat(grammageMatch[1]) : undefined;

  // Extract quality if mentioned
  let quality: string | undefined;
  for (const q of QUALITY_GRADES) {
    if (lowerQuery.includes(q.toLowerCase())) {
      quality = q;
      break;
    }
  }

  return queryFabricSpecs({ size, grammage, quality });
}
