/**
 * Calculate price for fabric based on parameters
 * 
 * @param basePriceForQuality - Base price for the specific quality grade at 13" (set by owner daily)
 * @param size - Size in inches
 * @param grammage - Grammage in grams per meter
 * @param quality - Quality grade
 * @param color - Color type
 * @param lamination - Lamination type
 * @returns Calculated price per kg
 */
export function calculateFabricPrice(
  basePriceForQuality: number,  // Owner sets this for 13" fabric of this quality
  size: string,
  grammage: number,
  quality: string,
  color: "white" | "half_colored" | "full_colored",
  lamination: "unlaminated" | "regular_lamination" | "natural_lamination"
): number {
  let price = basePriceForQuality;
  
  // Apply size premium (relative to 13" base)
  // Note: 13" is the base, so we need to calculate premium/discount for other sizes
  const sizeNum = parseInt(size);
  if (sizeNum > 13) {
    // Larger sizes have no premium (most are cheaper due to higher production)
    // No adjustment needed for 24-36"
  } else if (sizeNum === 13) {
    // This is the base size, no adjustment
  } else {
    // Smaller sizes have premiums
    if (PRICING_PREMIUMS.size[size]) {
      price += PRICING_PREMIUMS.size[size];
    }
  }
  
  // Apply grammage discount/premium
  const grammageKey = grammage.toFixed(1);
  if (PRICING_PREMIUMS.grammage[grammageKey] !== undefined) {
    price += PRICING_PREMIUMS.grammage[grammageKey];
  }
  
  // Apply color premium
  price += PRICING_PREMIUMS.color[color];
  
  // Apply lamination premium
  price += PRICING_PREMIUMS.lamination[lamination];
  
  return price;
}

/**
 * Load fabric knowledge into database
 */
export async function loadFabricKnowledge(): Promise<void> {
  const db = getDatabase();
  
  try {
    let loaded = 0;
    let skipped = 0;

    // Store fabric specifications
    for (const fabric of FABRIC_CATALOG) {
      const key = `fabric_${fabric.size_inches}inch_${fabric.grammage_gpm}gpm_${fabric.quality.toLowerCase()}`;
      
      const value = `PP Woven Fabric | Size: ${fabric.size_inches}" | Grammage: ${fabric.grammage_gpm}g/m (${fabric.denier} denier) | Quality: ${fabric.quality} | Meter Weight (Unlaminated): ${fabric.meter_weight_unlaminated}kg | Meter Weight (Laminated): ${fabric.meter_weight_laminated}kg`;

      const existing = db.prepare(`SELECT id FROM knowledge_base WHERE key = ?`).get(key);

      if (!existing) {
        db.prepare(`
          INSERT INTO knowledge_base (id, key, value, type, scope, source, created_at, updated_at)
          VALUES (?, ?, ?, 'fabric_spec', 'customer_visible', 'system', datetime('now'), datetime('now'))
        `).run(crypto.randomUUID(), key, value);
        loaded++;
      } else {
        skipped++;
      }
    }

    // Store pricing information
    const pricingInfo = {
      key: "fabric_pricing_rules",
      value: JSON.stringify(PRICING_PREMIUMS),
      type: "pricing_rules",
      scope: "internal_only",
    };

    const existingPricing = db.prepare(`SELECT id FROM knowledge_base WHERE key = ?`).get(pricingInfo.key);
    if (!existingPricing) {
      db.prepare(`
        INSERT INTO knowledge_base (id, key, value, type, scope, source, created_at, updated_at)
        VALUES (?, ?, ?, ?, ?, 'system', datetime('now'), datetime('now'))
      `).run(crypto.randomUUID(), pricingInfo.key, pricingInfo.value, pricingInfo.type, pricingInfo.scope);
      loaded++;
    }

    await appendLog("fabric_knowledge_loaded", {
      total: FABRIC_CATALOG.length + 1,
      loaded,
      skipped,
      message: `Fabric knowledge loaded: ${loaded} new specs, ${skipped} existing`,
    });

    console.log(`✅ Fabric Knowledge loaded: ${loaded} new specs, ${skipped} already existed`);
  } catch (error) {
    await appendLog("fabric_knowledge_load_failed", {
      error: error instanceof Error ? error.message : String(error),
    });
    throw error;
  }
}

