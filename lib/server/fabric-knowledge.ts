/**
 * Fabric Specification Type
 * Based on the Excel meter weight data sheets
 */
export type FabricSpec = {
  size_inches: string;              // Width: 36", 35", 34"... down to 12"
  grammage_gpm: number;             // Grams per meter: 3.0, 3.5, 4.0, 4.5, 5.0
  denier: number;                   // Thread thickness: 640, 747, 854, 960, 1067
  quality: string;                  // Janta, Regular, Silver, Gold, Platinum
  strength: string;                 // Strength range (e.g., "28-25", "30-35")
  elongation: string;               // Elongation percentage (e.g., "15-18%")
  meter_weight_unlaminated: number; // Meter weight without lamination (grams)
  meter_weight_laminated: number;   // Meter weight with lamination (grams)
  pp_percent: number;               // PP (Polypropylene) percentage
  filler_percent: number;           // Filler percentage
  category: "fabric_roll";
};

